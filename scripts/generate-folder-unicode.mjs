// Regenerate with UnicodeData.txt and CaseFolding.txt from
// https://www.unicode.org/Public/15.0.0/ucd/ as the two command arguments.
// Both runtimes must use this same pinned repertoire and full default folding.
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const sources = process.argv.slice(2).map((file) => readFileSync(file, "utf8"));
const hashes = [
  "806e9aed65037197f1ec85e12be6e8cd870fc5608b4de0fffd990f689f376a73",
  "cdd49e55eae3bbf1f0a3f6580c974a0263cb86a6a08daa10fbf705b4808a56f7",
];
if (sources.length !== 2 || sources.some((source, i) => createHash("sha256").update(source).digest("hex") !== hashes[i])) {
  throw new Error("Expected the unmodified Unicode 15.0.0 data files");
}
const assigned = [];
const marks = [];
function addRange(ranges, start, end) {
  const last = ranges.at(-1);
  if (last && last[1] + 1 === start) last[1] = end;
  else ranges.push([start, end]);
}
let first;
for (const line of sources[0].trim().split("\n")) {
  const fields = line.split(";");
  const code = parseInt(fields[0], 16);
  if (fields[1].endsWith(", First>")) { first = code; continue; }
  const start = fields[1].endsWith(", Last>") ? first : code;
  if (fields[2] === "Cs") continue;
  addRange(assigned, start, code);
  if (fields[2].startsWith("M")) addRange(marks, start, code);
}
const folds = {};
for (const line of sources[1].split("\n")) {
  const fields = line.split("#")[0].split(";").map((field) => field.trim());
  if (fields[1] !== "C" && fields[1] !== "F") continue;
  folds[parseInt(fields[0], 16)] = String.fromCodePoint(...fields[2].split(" ").map((code) => parseInt(code, 16)));
}
const data = { version: "15.0.0", assigned, marks, folds };
writeFileSync(new URL("../packages/core/attachments/unicode15-data.json", import.meta.url), JSON.stringify(data) + "\n");
const ranges = (name, values) => `var ${name} = [][2]rune{\n${values.map(([a, b]) => `\t{${a}, ${b}},`).join("\n")}\n}\n`;
// ASCII escaping keeps generated Go source independent of source-file controls.
const quote = (value) => JSON.stringify(value).replace(/[\u007f-\uffff]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
// Go strings cannot contain UTF-16 surrogate escapes; use scalar escapes.
const goQuote = (value) => [...value].map((c) => c.codePointAt(0) > 0xffff ? "\\U" + c.codePointAt(0).toString(16).padStart(8, "0") : quote(c).slice(1, -1)).join("");
writeFileSync(new URL("../server/internal/foldersnapshot/unicode15_generated.go", import.meta.url),
  "// Code generated by scripts/generate-folder-unicode.mjs; DO NOT EDIT.\n// Unicode 15.0.0. See the generator for source URLs and checksums.\n// License: packages/core/attachments/unicode15-LICENSE.txt (repository root).\npackage foldersnapshot\n\n"
  + ranges("assigned15", assigned) + "\n" + ranges("marks15", marks)
  + "\nvar folds15 = map[rune]string{\n" + Object.entries(folds).map(([code, value]) => `\t${code}: "${goQuote(value)}",`).join("\n") + "\n}\n");
execFileSync("gofmt", ["-w", new URL("../server/internal/foldersnapshot/unicode15_generated.go", import.meta.url).pathname]);
